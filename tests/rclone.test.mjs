import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { mkdir, readFile, writeFile, readdir, stat } from 'node:fs/promises';
import path from 'node:path';
import { bisyncArgs } from '../core/policy.mjs';
const exec=promisify(execFile);
const root=path.resolve(import.meta.dirname,'..');
const binary=process.env.CLOUDLANE_RCLONE || path.join(root,'.runtime/tools',process.platform==='win32'?'rclone.exe':'rclone');
const available=await stat(binary).then(s=>s.isFile()).catch(()=>false);
test('real rclone listing and bisync preview preserve both filesystems', {skip:!available}, async()=>{
  const fixture=path.join(root,'.runtime/i',crypto.randomUUID().slice(0,8));
  const remote=path.join(fixture,'r'), local=path.join(fixture,'l');
  await mkdir(remote,{recursive:true});await mkdir(local,{recursive:true});
  await writeFile(path.join(remote,'облако.txt'),'remote content');
  await writeFile(path.join(local,'локально.txt'),'local content');
  const config=path.join(fixture,'rclone.conf');
  await writeFile(config,`[cloud]\ntype = alias\nremote = ${remote}\n`);
  const flags=['--config',config,'--ask-password=false'];
  const {stdout}=await exec(binary,['lsjson','cloud:','--no-mimetype',...flags],{windowsHide:true});
  const list=JSON.parse(stdout);assert.equal(list[0].Name,'облако.txt');assert.equal(list[0].IsDir,false);
  const result=await exec(binary,[...bisyncArgs('cloud:',local,path.join(fixture,'work')),...flags],{windowsHide:true});
  assert.match(result.stdout+result.stderr,/dry.run|Skipped/i);
  assert.deepEqual(await readdir(remote),['облако.txt']);assert.deepEqual(await readdir(local),['локально.txt']);
  assert.equal(await readFile(path.join(remote,'облако.txt'),'utf8'),'remote content');
  assert.equal(await readFile(path.join(local,'локально.txt'),'utf8'),'local content');
});
