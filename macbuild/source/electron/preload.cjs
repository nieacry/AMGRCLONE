const { contextBridge, ipcRenderer } = require('electron');
const invoke = (name, ...args) => ipcRenderer.invoke('cloudlane:' + name, ...args);
contextBridge.exposeInMainWorld('cloudlane', Object.freeze({
  state: () => invoke('state'),
  setLanguage: language => invoke('setLanguage', language),
  setScope: (id, scope) => invoke('setScope', id, scope),
  setPreferences: input => invoke('setPreferences', input),
  quit: () => invoke('quit'),
  resetApp: confirmed => invoke('resetApp', confirmed),
  cleanupLegacy: id => invoke('cleanupLegacy', id),
  enableNativeRoot: id => invoke('enableNativeRoot', id),
  chooseNativeRoot: id => invoke('chooseNativeRoot', id),
  refreshNative: id => invoke('refreshNative', id),
  nativeItem: (id, path) => invoke('nativeItem', id, path),
  nativeItems: (id, paths) => invoke('nativeItems', id, paths),
  nativeAvailability: (id, path, mode) => invoke('nativeAvailability', id, path, mode),
  chooseDriveFolder: id => invoke('chooseDriveFolder', id),
  driveLetters: () => invoke('driveLetters'),
  createDrive: (id, path, letter) => invoke('createDrive', id, path, letter),
  removeDrive: id => invoke('removeDrive', id),
  chooseRclone: () => invoke('chooseRclone'),
  login: name => invoke('login', name),
  removeAccount: (id, confirmed) => invoke('removeAccount', id, confirmed),
  list: (id, path) => invoke('list', id, path),
  chooseRoot: id => invoke('chooseRoot', id),
  saveSettings: (id, settings) => invoke('saveSettings', id, settings),
  preview: (id, options) => invoke('preview', id, options),
  execute: (id, token, confirmed) => invoke('execute', id, token, confirmed),
  fileEvents: (id, options) => invoke('fileEvents', id, options),
  history: id => invoke('history', id),
  runLog: (id, runId) => invoke('runLog', id, runId),
  openLocal: id => invoke('openLocal', id),
  setSchedule: (id, minutes, paused) => invoke('setSchedule', id, minutes, paused),
  cancel: () => invoke('cancel')
}));
