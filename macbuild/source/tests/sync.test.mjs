import {test} from 'node:test';
import assert from 'node:assert/strict';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import {mkdir,readFile,writeFile,readdir,stat,unlink,utimes} from 'node:fs/promises';
import path from 'node:path';
import {SyncStore} from '../core/store.mjs';
import {SyncEngine} from '../core/sync-engine.mjs';
const exec=promisify(execFile),root=path.resolve(import.meta.dirname,'..');
const binary=process.env.CLOUDLANE_RCLONE||path.join(root,'.runtime/tools',process.platform==='win32'?'rclone.exe':'rclone');
const available=await stat(binary).then(s=>s.isFile()).catch(()=>false);
test('real engine: initial merge, backups, incremental changes, deletions, conflicts, stale plans and recovery',{skip:!available,timeout:180000},async()=>{
  const base=path.join(root,'.runtime/s',crypto.randomUUID().slice(0,6)),remote=path.join(base,'r'),local=path.join(base,'l');
  await mkdir(path.join(remote,'Projects'),{recursive:true});await mkdir(path.join(local,'Projects'),{recursive:true});
  for(let i=0;i<20;i++)await writeFile(path.join(remote,'Projects',`keep${i}.txt`),`original stable ${i}`);
  await writeFile(path.join(remote,'Projects','shared.txt'),'remote first version');await writeFile(path.join(local,'Projects','shared.txt'),'local version replaced and backed up');
  const config=path.join(base,'config.conf');await writeFile(config,`[cloud]\ntype = alias\nremote = ${remote}\n`);
  const calls=[];let failNextWrite=false;
  const run=async(args)=>{
    calls.push(args);
    if(failNextWrite&&args[0]==='bisync'&&!args.includes('--dry-run')){failNextWrite=false;throw new Error('err.canceled');}
    try{return await exec(binary,args,{windowsHide:true,maxBuffer:32*1024*1024});}catch(error){error.safeLog=error.stderr;throw error;}
  };
  const connection=async(_acc,callback)=>callback(['--config',config,'--ask-password=false']);
  const filename=path.join(base,'sync.sqlite');let store=new SyncStore(filename);let engine=new SyncEngine({store,dataDir:base,connection,run});
  const acc={id:'test-account',settings:{localRoot:local,rules:{Projects:{selected:true,mode:'local',kind:'folder'}}}};
  const preview=await engine.preview(acc,{strategy:'remote'});assert.equal(preview.jobs[0].initialization,true);
  assert.equal(await readFile(path.join(local,'Projects','shared.txt'),'utf8'),'local version replaced and backed up');
  await assert.rejects(()=>engine.execute(acc,preview.token,false),/err.confirm/);
  const initial=await engine.preview(acc,{strategy:'remote'});await engine.execute(acc,initial.token,true);
  assert.equal(await readFile(path.join(local,'Projects','shared.txt'),'utf8'),'remote first version');
  assert.equal(await readFile(path.join(initial.jobs[0].backupLocal,'shared.txt'),'utf8'),'local version replaced and backed up');
  assert.equal(store.jobs(acc.id)[0].status,'idle');assert.equal(store.history(acc.id)[0].status,'succeeded');
  await writeFile(path.join(local,'Projects','from-local.txt'),'upload me');await writeFile(path.join(remote,'Projects','from-cloud.txt'),'download me');
  await unlink(path.join(remote,'Projects','keep0.txt'));
  const incremental=await engine.preview(acc);assert.equal(incremental.jobs[0].initialization,false);
  await engine.execute(acc,incremental.token,true);
  assert.equal(await readFile(path.join(remote,'Projects','from-local.txt'),'utf8'),'upload me');
  assert.equal(await readFile(path.join(local,'Projects','from-cloud.txt'),'utf8'),'download me');
  assert.equal(await stat(path.join(local,'Projects','keep0.txt')).catch(()=>null),null);
  assert.equal(await readFile(path.join(incremental.jobs[0].backupLocal,'keep0.txt'),'utf8'),'original stable 0');
  const actualWrites=calls.filter(a=>a[0]==='bisync'&&!a.includes('--dry-run'));assert.ok(!actualWrites[1].includes('--resync'));
  const stale=await engine.preview(acc);await writeFile(path.join(local,'Projects','after-preview.txt'),'changed after preview');
  await assert.rejects(()=>engine.execute(acc,stale.token,true),/err.plan/);assert.equal(await stat(path.join(remote,'Projects','after-preview.txt')).catch(()=>null),null);
  const changedSettings=await engine.preview(acc);const original=acc.settings.rules.Projects.mode;acc.settings.rules.Projects.mode='online';
  await assert.rejects(()=>engine.execute(acc,changedSettings.token,true),/err.plan/);acc.settings.rules.Projects.mode=original;
  const beforeConflict=await engine.preview(acc);await engine.execute(acc,beforeConflict.token,true);
  await writeFile(path.join(remote,'Projects','shared.txt'),'changed remote conflict content');await writeFile(path.join(local,'Projects','shared.txt'),'changed local conflicting version with a different length');
  const future=new Date(Date.now()+3000);await utimes(path.join(remote,'Projects','shared.txt'),future,future);
  const conflict=await engine.preview(acc);await engine.execute(acc,conflict.token,true);
  const texts=await Promise.all((await readdir(path.join(local,'Projects'))).filter(n=>n.startsWith('shared')).map(n=>readFile(path.join(local,'Projects',n),'utf8')));
  assert.ok(texts.includes('changed remote conflict content'));assert.ok(texts.includes('changed local conflicting version with a different length'));
  const interrupted=await engine.preview(acc);failNextWrite=true;await assert.rejects(()=>engine.execute(acc,interrupted.token,true),/err.canceled/);
  assert.equal(store.jobs(acc.id)[0].status,'needsReview');
  await assert.rejects(()=>engine.preview(acc),/err.recovery/);
  const recovered=await engine.preview(acc,{strategy:'remote',recovery:true});assert.equal(recovered.jobs[0].recovery,true);await engine.execute(acc,recovered.token,true);
  assert.equal(store.jobs(acc.id)[0].status,'idle');
  const marker=store.jobs(acc.id)[0].marker;await unlink(path.join(remote,'Projects',marker));
  await assert.rejects(()=>engine.preview(acc),/err.marker/);assert.equal(store.jobs(acc.id)[0].status,'needsReview');
  const markerRecovery=await engine.preview(acc,{recovery:true});await engine.execute(acc,markerRecovery.token,true);
  store.close();store=new SyncStore(filename);engine=new SyncEngine({store,dataDir:base,connection,run});
  const reopened=await engine.preview(acc);assert.equal(reopened.jobs[0].initialization,false);
  // A moved/deleted root cannot silently become a new Dropbox folder.
  store.db.prepare("UPDATE jobs SET item_id='different-id'").run();await assert.rejects(()=>engine.preview(acc),/err.identity/);
  store.close();
});
